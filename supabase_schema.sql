-- Promedio de calificación de fincas
CREATE OR REPLACE FUNCTION public."SP_PromedioCalificacionFincas"()
RETURNS TABLE (
    "IdFinca" INT,
    "NombreFinca" VARCHAR(300),
    "PromedioCalificacion" DOUBLE PRECISION
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        f."IdFinca",
        f."NombreFinca", 
        ROUND(AVG(f."Calificacion")::NUMERIC, 2)::DOUBLE PRECISION AS "PromedioCalificacion"
    FROM public."Finca" f
    WHERE f."Calificacion" IS NOT NULL
    GROUP BY f."IdFinca", f."NombreFinca"
    ORDER BY "PromedioCalificacion" DESC;
END;
$$;

-- Total ingresos por finca
CREATE OR REPLACE FUNCTION public."SP_TotalIngresosPorFinca"()
RETURNS TABLE (
    "IdFinca" INT,
    "NombreFinca" VARCHAR(300),
    "TotalIngresos" BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        f."IdFinca",
        f."NombreFinca", 
        COALESCE(SUM(p."Monto"), 0)::BIGINT AS "TotalIngresos"
    FROM public."Pago" p
    INNER JOIN public."Factura" fa ON p."IdFactura" = fa."IdFactura"
    INNER JOIN public."Reserva" r ON fa."IdReserva" = r."IdReserva"
    INNER JOIN public."Finca" f ON r."IdFinca" = f."IdFinca"
    WHERE p."EstadoPago" = 'Pagado'
    GROUP BY f."IdFinca", f."NombreFinca"
    ORDER BY "TotalIngresos" DESC;
END;
$$;

