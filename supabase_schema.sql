-- Listar roles
CREATE OR REPLACE FUNCTION public."SP_ListarRol"()
RETURNS TABLE (
    "IdRol" INT,
    "NombreRol" VARCHAR(300)
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT r."IdRol", r."NombreRol"
    FROM public."Rol" r
    ORDER BY r."IdRol" ASC;
END;
$$;

-- Insertar rol (retorna IdRol generado)
CREATE OR REPLACE FUNCTION public."SP_InsertarRol"(
    "p_NombreRol" VARCHAR(300)
)
RETURNS INT
LANGUAGE plpgsql
AS $$
DECLARE
    v_id INT;
BEGIN
    INSERT INTO public."Rol" ("NombreRol")
    VALUES ("p_NombreRol")
    RETURNING "IdRol" INTO v_id;
    RETURN v_id;
END;
$$;

-- Actualizar rol
CREATE OR REPLACE FUNCTION public."SP_ActualizarRol"(
    "p_IdRol" INT,
    "p_NombreRol" VARCHAR(300)
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE public."Rol"
    SET "NombreRol" = "p_NombreRol"
    WHERE "IdRol" = "p_IdRol";
END;
$$;

-- Eliminar rol
CREATE OR REPLACE FUNCTION public."SP_EliminarRol"(
    "p_IdRol" INT
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    DELETE FROM public."Rol"
    WHERE "IdRol" = "p_IdRol";
END;
$$;

