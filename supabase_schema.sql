-- Iniciar sesión
CREATE OR REPLACE FUNCTION public."SP_IniciarSesion"(
    "p_Correo" VARCHAR(500),
    "p_Contrasena" VARCHAR(300)
)
RETURNS TABLE (
    "NumeroDocumento" INT,
    "IdRol" INT,
    "NombreUsuario" VARCHAR(300),
    "ApellidoUsuario" VARCHAR(300),
    "Telefono" VARCHAR(100),
    "Correo" VARCHAR(500),
    "Estado" VARCHAR(150),
    "NombreRol" VARCHAR(300)
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT 
        u."NumeroDocumento",
        u."IdRol",
        u."NombreUsuario",
        u."ApellidoUsuario",
        u."Telefono",
        u."Correo",
        u."Estado",
        r."NombreRol"
    FROM public."Usuario" u
    LEFT JOIN public."Rol" r ON u."IdRol" = r."IdRol"
    WHERE LOWER(u."Correo") = LOWER("p_Correo")
      AND u."Contrasena" = "p_Contrasena"
      AND u."Estado" = 'Activo';
END;
$$;

