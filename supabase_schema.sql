-- Fincas más reservadas
CREATE OR REPLACE FUNCTION public."SP_FincasMasReservadas"()
RETURNS TABLE (
    "IdFinca" INT,
    "NombreFinca" VARCHAR(300),
    "CantidadReservas" BIGINT
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
