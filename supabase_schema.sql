-- =============================================================================
-- 3. CREACIÓN DE TABLAS CON IDENTIFICADORES EXACTOS (PASCALCASE)
-- =============================================================================

-- Tabla: Rol
CREATE TABLE public."Rol" (
    "IdRol" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NombreRol" VARCHAR(300) NOT NULL
);

-- Tabla: Usuario
CREATE TABLE public."Usuario" (
    "NumeroDocumento" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdRol" INT REFERENCES public."Rol"("IdRol") ON UPDATE CASCADE ON DELETE SET NULL,
    "NombreUsuario" VARCHAR(300) NOT NULL,
    "ApellidoUsuario" VARCHAR(300) NOT NULL,
    "Telefono" VARCHAR(100),
    "Contrasena" VARCHAR(300) NOT NULL,
    "Correo" VARCHAR(500) NOT NULL UNIQUE,
    "Estado" VARCHAR(150) DEFAULT 'Activo'
);

-- Tabla: Municipio
CREATE TABLE public."Municipio" (
    "IdMunicipio" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NombreMunicipio" VARCHAR(150) NOT NULL
);

-- Tabla: Finca
CREATE TABLE public."Finca" (
    "IdFinca" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdMunicipio" INT REFERENCES public."Municipio"("IdMunicipio") ON UPDATE CASCADE ON DELETE SET NULL,
    "NumeroDocumentoUsuario" INT REFERENCES public."Usuario"("NumeroDocumento") ON UPDATE CASCADE ON DELETE SET NULL,
    "NombreFinca" VARCHAR(300) NOT NULL,
    "Direccion" VARCHAR(500),
    "InformacionAdicional" VARCHAR(500),
    "Capacidad" INT DEFAULT 1,
    "Precio" INT DEFAULT 0,
    "Estado" VARCHAR(150) DEFAULT 'Disponible',
    "Calificacion" INT DEFAULT 5
);

-- Tabla: Imagen
CREATE TABLE public."Imagen" (
    "IdImagen" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UrlImagen" VARCHAR(500) NOT NULL,
    "IdFinca" INT REFERENCES public."Finca"("IdFinca") ON UPDATE CASCADE ON DELETE CASCADE
);

-- Tabla: MetodoDePago
CREATE TABLE public."MetodoDePago" (
    "IdMetodoDePago" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NombreMetodoDePago" VARCHAR(150) NOT NULL,
    "PagoMixto" BOOLEAN DEFAULT FALSE
);

-- Tabla: Reserva
CREATE TABLE public."Reserva" (
    "IdReserva" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdFinca" INT REFERENCES public."Finca"("IdFinca") ON UPDATE CASCADE ON DELETE CASCADE,
    "NumeroDocumentoUsuario" INT REFERENCES public."Usuario"("NumeroDocumento") ON UPDATE CASCADE ON DELETE SET NULL,
    "FechaReserva" TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "FechaEntrada" TIMESTAMP WITHOUT TIME ZONE,
    "FechaSalida" TIMESTAMP WITHOUT TIME ZONE,
    "Estado" VARCHAR(150) DEFAULT 'Pendiente',
    "MontoReserva" INT DEFAULT 0
);

-- Tabla: Factura
CREATE TABLE public."Factura" (
    "IdFactura" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdReserva" INT REFERENCES public."Reserva"("IdReserva") ON UPDATE CASCADE ON DELETE CASCADE,
    "FechaFactura" TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "Total" INT DEFAULT 0
);

-- Tabla: Pago
CREATE TABLE public."Pago" (
    "IdPago" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdFactura" INT REFERENCES public."Factura"("IdFactura") ON UPDATE CASCADE ON DELETE CASCADE,
    "IdMetodoDePago" INT REFERENCES public."MetodoDePago"("IdMetodoDePago") ON UPDATE CASCADE ON DELETE SET NULL,
    "Monto" INT DEFAULT 0,
    "FechaPago" TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    "EstadoPago" VARCHAR(150) DEFAULT 'Pendiente'
);

