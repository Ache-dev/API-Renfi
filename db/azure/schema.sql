CREATE VIEW vw_usuario AS
SELECT u."NumeroDocumento", u."IdRol", u."NombreUsuario", u."ApellidoUsuario", u."Telefono",
       u."Correo", u."Contrasena", u."Estado", r."NombreRol"
FROM "Usuario" u LEFT JOIN "Rol" r ON r."IdRol" = u."IdRol";

CREATE VIEW vw_finca AS
SELECT f."IdFinca", f."IdMunicipio", f."NumeroDocumentoUsuario", f."NombreFinca", f."Direccion",
       f."InformacionAdicional", f."Capacidad", f."Precio", f."Estado", f."Calificacion",
       f."Habitaciones", f."Banos", f."Camas", f."NochesMinimas", f."Comodidades", f."Reglas",
       to_char(f."HoraEntrada", 'HH24:MI') AS "HoraEntrada",
       to_char(f."HoraSalida", 'HH24:MI')  AS "HoraSalida",
       f."PermiteMascotas", f."PermiteEventos", f."Latitud", f."Longitud",
       m."NombreMunicipio",
       u."NumeroDocumento" AS "IdPropietario",
       u."NombreUsuario"   AS "NombrePropietario",
       u."ApellidoUsuario" AS "ApellidoPropietario",
       u."Telefono"        AS "TelefonoPropietario",
       u."Correo"          AS "CorreoPropietario",
       u."NombreUsuario"   AS "Dueno",
       -- Galería: portada primero, luego por orden
       COALESCE((SELECT jsonb_agg(jsonb_build_object(
                    'IdImagen', i."IdImagen", 'RutaStorage', i."RutaStorage", 'IdFinca', i."IdFinca",
                    'Orden', i."Orden", 'EsPortada', i."EsPortada", 'TextoAlternativo', i."TextoAlternativo",
                    'Ancho', i."Ancho", 'Alto', i."Alto")
                    ORDER BY i."EsPortada" DESC, i."Orden", i."IdImagen")
                 FROM "Imagen" i WHERE i."IdFinca" = f."IdFinca"), '[]'::jsonb) AS "Imagenes"
FROM "Finca" f
LEFT JOIN "Municipio" m ON m."IdMunicipio" = f."IdMunicipio"
LEFT JOIN "Usuario"   u ON u."NumeroDocumento" = f."NumeroDocumentoUsuario";

CREATE VIEW vw_reserva AS
SELECT r."IdReserva", r."IdFinca", r."NumeroDocumentoUsuario", r."FechaReserva", r."FechaEntrada",
       r."FechaSalida", r."Estado", r."MontoReserva",
       f."NombreFinca", f."Precio" AS "PrecioFinca", f."Estado" AS "EstadoFinca", f."Capacidad",
       m."NombreMunicipio",
       p."NumeroDocumento" AS "IdPropietario", p."NombreUsuario" AS "NombrePropietario",
       p."ApellidoUsuario" AS "ApellidoPropietario", p."Telefono" AS "TelefonoPropietario",
       c."NumeroDocumento" AS "NumeroDocumentoCliente", c."NombreUsuario" AS "NombreCliente",
       c."ApellidoUsuario" AS "ApellidoCliente", c."Telefono" AS "TelefonoCliente", c."Correo" AS "CorreoCliente"
FROM "Reserva" r
LEFT JOIN "Finca"     f ON f."IdFinca" = r."IdFinca"
LEFT JOIN "Municipio" m ON m."IdMunicipio" = f."IdMunicipio"
LEFT JOIN "Usuario"   p ON p."NumeroDocumento" = f."NumeroDocumentoUsuario"
LEFT JOIN "Usuario"   c ON c."NumeroDocumento" = r."NumeroDocumentoUsuario";

CREATE VIEW vw_factura AS
SELECT fa."IdFactura", fa."IdReserva", fa."FechaFactura", fa."Total",
       r."NumeroDocumentoUsuario" AS "NumeroDocumentoCliente", r."FechaReserva", r."Estado" AS "EstadoReserva",
       f."IdFinca", f."NombreFinca", f."Precio" AS "PrecioFinca", m."NombreMunicipio",
       p."NumeroDocumento" AS "IdPropietario", p."NombreUsuario" AS "NombrePropietario",
       p."ApellidoUsuario" AS "ApellidoPropietario"
FROM "Factura" fa
LEFT JOIN "Reserva"   r ON r."IdReserva" = fa."IdReserva"
LEFT JOIN "Finca"     f ON f."IdFinca" = r."IdFinca"
LEFT JOIN "Municipio" m ON m."IdMunicipio" = f."IdMunicipio"
LEFT JOIN "Usuario"   p ON p."NumeroDocumento" = f."NumeroDocumentoUsuario";

CREATE VIEW vw_pago AS
SELECT pa."IdPago", pa."IdFactura", pa."IdMetodoDePago", pa."Monto", pa."FechaPago", pa."EstadoPago",
       mp."NombreMetodoDePago", mp."PagoMixto",
       fa."FechaFactura", fa."Total" AS "TotalFactura", fa."IdReserva",
       r."NumeroDocumentoUsuario" AS "NumeroDocumentoCliente", r."Estado" AS "EstadoReserva",
       f."IdFinca", f."NombreFinca", f."Precio" AS "PrecioFinca", m."NombreMunicipio",
       p."NumeroDocumento" AS "IdPropietario", p."NombreUsuario" AS "NombrePropietario",
       p."ApellidoUsuario" AS "ApellidoPropietario"
FROM "Pago" pa
LEFT JOIN "MetodoDePago" mp ON mp."IdMetodoDePago" = pa."IdMetodoDePago"
LEFT JOIN "Factura"      fa ON fa."IdFactura" = pa."IdFactura"
LEFT JOIN "Reserva"      r  ON r."IdReserva" = fa."IdReserva"
LEFT JOIN "Finca"        f  ON f."IdFinca" = r."IdFinca"
LEFT JOIN "Municipio"    m  ON m."IdMunicipio" = f."IdMunicipio"
LEFT JOIN "Usuario"      p  ON p."NumeroDocumento" = f."NumeroDocumentoUsuario";

CREATE VIEW vw_imagen AS
SELECT i."IdImagen", i."RutaStorage", i."IdFinca", i."Orden", i."EsPortada", i."TextoAlternativo",
       i."TipoMime", i."TamanoBytes", i."Ancho", i."Alto", i."FechaCreacion", f."NombreFinca"
FROM "Imagen" i LEFT JOIN "Finca" f ON f."IdFinca" = i."IdFinca";

-- =============================================================================
-- 6. PROCEDIMIENTOS ALMACENADOS (único punto de acceso de la API a los datos)
--    Convenciones: sp_<entidad>_<accion>. Los que consultan devuelven jsonb (una fila por
--    elemento) con los campos ya aplanados; los que insertan devuelven el Id generado
--    (INSERT ... RETURNING); los que modifican devuelven void. Los errores de SQLSTATE
--    (23505, 23514, 23P01, 22001...) llegan intactos a error.middleware.
-- =============================================================================

-- Los listados sin acotar llevan un tope duro (p_limite, 1000 por defecto) para que una tabla grande no
-- produzca respuestas gigantes (CPU, ancho de banda y memoria). La API avisa en el log si un listado lo alcanza.

-- ---------- Rol ----------
CREATE FUNCTION sp_rol_listar() RETURNS SETOF jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT to_jsonb(r) FROM "Rol" r ORDER BY "IdRol";
$$;
CREATE FUNCTION sp_rol_buscar(p_id int) RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT to_jsonb(r) FROM "Rol" r WHERE "IdRol" = p_id;
$$;
CREATE FUNCTION sp_rol_insertar(p_nombre text) RETURNS int LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
    INSERT INTO "Rol" ("NombreRol") VALUES (p_nombre) RETURNING "IdRol";
$$;
CREATE FUNCTION sp_rol_actualizar(p_id int, p_nombre text) RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
    UPDATE "Rol" SET "NombreRol" = p_nombre WHERE "IdRol" = p_id;
$$;
CREATE FUNCTION sp_rol_eliminar(p_id int) RETURNS void LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
    DELETE FROM "Rol" WHERE "IdRol" = p_id;
$$;
CREATE FUNCTION sp_rol_contar_usuarios(p_id int) RETURNS int LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT count(*)::int FROM "Usuario" WHERE "IdRol" = p_id;
$$;

-- ---------- Municipio ----------
CREATE FUNCTION sp_municipio_listar() RETURNS SETOF jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT to_jsonb(m) FROM "Municipio" m ORDER BY "IdMunicipio";
$$;
CREATE FUNCTION sp_municipio_buscar(p_id int) RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS $$
    SELECT to_jsonb(m) FROM "Municipio" m WHERE "IdMunicipio" = p_id;
$$;
CREATE FUNCTION sp_municipio_insertar(p_nombre text) RETURNS int LANGUAGE sql SECURITY DEFINER SET search_path = public, pg_temp AS $$
    INSERT INTO "Municipio" ("NombreMunicipio") VALUES (p_nombre) RETURNING "IdMunicipio";
$$;
