CREATE TABLE "Municipio" (
    "IdMunicipio"     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "NombreMunicipio" VARCHAR(150) NOT NULL
);

CREATE TABLE "Finca" (
    "IdFinca"                INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdMunicipio"            INT REFERENCES "Municipio"("IdMunicipio") ON UPDATE CASCADE ON DELETE SET NULL,
    "NumeroDocumentoUsuario" INT REFERENCES "Usuario"("NumeroDocumento") ON UPDATE CASCADE ON DELETE SET NULL,
    "NombreFinca"            VARCHAR(300) NOT NULL,
    "Direccion"              VARCHAR(500),
    "InformacionAdicional"   VARCHAR(500),
    "Capacidad"              INT DEFAULT 1,
    "Precio"                 INT DEFAULT 0,
    "Estado"                 VARCHAR(150) DEFAULT 'Disponible',
    "Calificacion"           INT DEFAULT 5,
    -- Ficha completa
    "Habitaciones"           INT           NOT NULL DEFAULT 1,
    "Banos"                  INT           NOT NULL DEFAULT 1,
    "Camas"                  INT           NOT NULL DEFAULT 1,
    "NochesMinimas"          INT           NOT NULL DEFAULT 1,
    "Comodidades"            TEXT[]        NOT NULL DEFAULT '{}',
    "Reglas"                 TEXT,
    "HoraEntrada"            TIME          NOT NULL DEFAULT '15:00',
    "HoraSalida"             TIME          NOT NULL DEFAULT '11:00',
    "PermiteMascotas"        BOOLEAN       NOT NULL DEFAULT FALSE,
    "PermiteEventos"         BOOLEAN       NOT NULL DEFAULT FALSE,
    "Latitud"                NUMERIC(9,6),
    "Longitud"               NUMERIC(9,6),
    "FechaCreacion"          TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
