-- Agrega la imagen al final de la galería; si es portada, deja sin portada a las demás.
-- Todo en una transacción; el bloqueo de la finca evita dos altas simultáneas con el mismo Orden.
CREATE FUNCTION sp_imagen_insertar(p_finca int, p_ruta text, p_portada boolean, p_alt text, p_mime text, p_tamano int, p_ancho int, p_alto int)
RETURNS int LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
DECLARE
    v_orden int;
    v_id int;
BEGIN
    PERFORM 1 FROM "Finca" WHERE "IdFinca" = p_finca FOR NO KEY UPDATE;
    -- Mismo tope que MAX_IMAGENES_POR_FINCA en src/services/imagen.service.ts (aquí a prueba de subidas simultáneas)
    IF (SELECT count(*) FROM "Imagen" WHERE "IdFinca" = p_finca) >= 10 THEN
        RAISE EXCEPTION 'Cada finca admite máximo 10 imágenes. Elimina alguna antes de subir otra.';
    END IF;
    SELECT COALESCE(MAX("Orden"), 0) + 1 INTO v_orden FROM "Imagen" WHERE "IdFinca" = p_finca;
    IF p_portada THEN
        UPDATE "Imagen" SET "EsPortada" = FALSE WHERE "IdFinca" = p_finca AND "EsPortada";
    END IF;
    INSERT INTO "Imagen" ("IdFinca", "RutaStorage", "Orden", "EsPortada", "TextoAlternativo", "TipoMime", "TamanoBytes", "Ancho", "Alto")
    VALUES (p_finca, p_ruta, v_orden, p_portada, p_alt, p_mime, p_tamano, p_ancho, p_alto)
    RETURNING "IdImagen" INTO v_id;
    RETURN v_id;
END $$;
-- p_campos: solo lo que cambia (IdFinca, EsPortada, TextoAlternativo, Orden). Asignar portada
-- deja sin portada a las demás imágenes de p_finca.
CREATE FUNCTION sp_imagen_actualizar(p_id int, p_finca int, p_campos jsonb) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS $$
BEGIN
    IF (p_campos->>'EsPortada')::boolean IS TRUE THEN
        UPDATE "Imagen" SET "EsPortada" = FALSE WHERE "IdFinca" = p_finca AND "EsPortada";
    END IF;
    UPDATE "Imagen" SET
        "IdFinca"          = CASE WHEN p_campos ? 'IdFinca'          THEN (p_campos->>'IdFinca')::int ELSE "IdFinca" END,
        "EsPortada"        = CASE WHEN p_campos ? 'EsPortada'        THEN (p_campos->>'EsPortada')::boolean ELSE "EsPortada" END,
        "TextoAlternativo" = CASE WHEN p_campos ? 'TextoAlternativo' THEN p_campos->>'TextoAlternativo' ELSE "TextoAlternativo" END,
        "Orden"            = CASE WHEN p_campos ? 'Orden'            THEN (p_campos->>'Orden')::int ELSE "Orden" END
    WHERE "IdImagen" = p_id;
END $$;
