-- Longitud del elemento más largo de una lista de textos (los CHECK no admiten subconsultas)
CREATE FUNCTION fn_longitud_maxima(p_lista text[]) RETURNS int
LANGUAGE sql IMMUTABLE SET search_path = pg_catalog AS $$
    SELECT COALESCE(max(char_length(x)), 0)::int FROM unnest(p_lista) AS x;
$$;

ALTER TABLE "Usuario"
    ADD CONSTRAINT ck_usuario_nombres CHECK (char_length(btrim("NombreUsuario")) BETWEEN 1 AND 100
        AND char_length(btrim("ApellidoUsuario")) BETWEEN 1 AND 100),
    ADD CONSTRAINT ck_usuario_correo CHECK ("Correo" = lower(btrim("Correo")) AND "Correo" ~ '^[^\s@]+@[^\s@]+\.[^\s@]+$'),
    ADD CONSTRAINT ck_usuario_telefono CHECK ("Telefono" IS NULL OR "Telefono" = '' OR "Telefono" ~ '^\+?[0-9 ()-]{7,20}$'),
    -- Solo hashes bcrypt: nunca una contraseña en texto plano
    ADD CONSTRAINT ck_usuario_contrasena CHECK ("Contrasena" LIKE '$2%'),
    ADD CONSTRAINT ck_usuario_estado CHECK ("Estado" IN ('Activo', 'Inactivo'));

ALTER TABLE "Rol"          ADD CONSTRAINT ck_rol_nombre       CHECK (char_length(btrim("NombreRol")) >= 1);
ALTER TABLE "Municipio"    ADD CONSTRAINT ck_municipio_nombre CHECK (char_length(btrim("NombreMunicipio")) >= 1);
ALTER TABLE "MetodoDePago" ADD CONSTRAINT ck_metodo_nombre    CHECK (char_length(btrim("NombreMetodoDePago")) >= 1);

ALTER TABLE "Finca"
    ADD CONSTRAINT ck_finca_basicos CHECK (char_length(btrim("NombreFinca")) >= 1
        AND "Precio" BETWEEN 1 AND 20000000
        AND "Capacidad" BETWEEN 1 AND 500
        AND "Calificacion" BETWEEN 1 AND 5
        AND "Estado" IN ('Disponible', 'No disponible')
        AND cardinality("Comodidades") <= 30
        AND fn_longitud_maxima("Comodidades") <= 50),
    ADD CONSTRAINT ck_finca_ficha CHECK (
        "Habitaciones" BETWEEN 0 AND 100
        AND "Banos" BETWEEN 0 AND 100
        AND "Camas" BETWEEN 0 AND 200
        AND "NochesMinimas" BETWEEN 1 AND 30
        AND ("Reglas" IS NULL OR char_length("Reglas") <= 1000)
        AND ("Latitud" IS NULL OR "Latitud" BETWEEN -90 AND 90)
        AND ("Longitud" IS NULL OR "Longitud" BETWEEN -180 AND 180)
        AND (("Latitud" IS NULL) = ("Longitud" IS NULL)));

-- Precio máximo x 90 noches cabe en un INT: el monto nunca desborda
ALTER TABLE "Reserva"
    ADD CONSTRAINT ck_reserva_fechas CHECK ("FechaEntrada" IS NOT NULL AND "FechaSalida" IS NOT NULL
        AND "FechaSalida" > "FechaEntrada"
        AND "FechaSalida" - "FechaEntrada" <= INTERVAL '90 days'),
    ADD CONSTRAINT ck_reserva_monto  CHECK ("MontoReserva" > 0),
    ADD CONSTRAINT ck_reserva_estado CHECK ("Estado" IN ('Pendiente', 'Activa', 'Confirmada', 'Finalizada', 'Cancelada')),
    -- Dos reservas vivas de la misma finca no pueden compartir noches, ni con peticiones simultáneas
    ADD CONSTRAINT ex_reserva_sin_solape EXCLUDE USING gist ("IdFinca" WITH =, tsrange("FechaEntrada", "FechaSalida") WITH &&)
        WHERE (lower("Estado") NOT IN ('cancelada', 'cancelado', 'anulada', 'anulado'));

-- Límites de almacenamiento: nada de archivos o metadatos fuera de lo que la API produce
ALTER TABLE "Imagen"
    ADD CONSTRAINT ck_imagen_limites CHECK (
        char_length(btrim("RutaStorage")) >= 1
        AND "Orden" BETWEEN 0 AND 1000
        AND ("TamanoBytes" IS NULL OR "TamanoBytes" BETWEEN 1 AND 5242880)
        AND ("Ancho" IS NULL OR "Ancho" BETWEEN 1 AND 4000)
        AND ("Alto" IS NULL OR "Alto" BETWEEN 1 AND 4000));

