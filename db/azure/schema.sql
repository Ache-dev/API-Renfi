ALTER TABLE "Pago"
    ADD CONSTRAINT ck_pago_monto  CHECK ("Monto" > 0),
    ADD CONSTRAINT ck_pago_estado CHECK ("EstadoPago" IN ('Pendiente', 'Pagado', 'Rechazado'));

