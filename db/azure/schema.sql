-- 8. PERMISOS: la API solo ejecuta sp_*
--    Crea el rol de la API una vez (como administrador), ANTES o DESPUÉS de este script:
--        CREATE ROLE renfi_app LOGIN PASSWORD '<contraseña-larga>';
--    y usa ese rol en DATABASE_URL. Si ya existe, este bloque le da EXECUTE sobre los sp_*.
--    Ni tablas ni vistas son accesibles para renfi_app.
-- =============================================================================
REVOKE ALL ON ALL TABLES    IN SCHEMA public FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC;

DO $$
DECLARE f record;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'renfi_app') THEN
        GRANT USAGE ON SCHEMA public TO renfi_app;
        -- Topes de recursos para el rol de la API: aunque la API se descontrole, la base no se satura ni cobra de más
        ALTER ROLE renfi_app CONNECTION LIMIT 30;
        ALTER ROLE renfi_app SET statement_timeout = '15s';
        ALTER ROLE renfi_app SET lock_timeout = '5s';
        ALTER ROLE renfi_app SET idle_in_transaction_session_timeout = '10s';
        FOR f IN SELECT p.oid::regprocedure AS firma FROM pg_proc p
                 WHERE p.pronamespace = 'public'::regnamespace AND p.proname LIKE 'sp\_%'
        LOOP
            EXECUTE 'GRANT EXECUTE ON FUNCTION ' || f.firma || ' TO renfi_app';
        END LOOP;
    ELSE
        RAISE NOTICE 'El rol renfi_app no existe: créalo y vuelve a ejecutar la sección 8 para darle EXECUTE sobre los sp_*.';
    END IF;
END $$;
