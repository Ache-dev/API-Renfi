-- =============================================================================
-- RENFI - ESQUEMA PARA AZURE DATABASE FOR POSTGRESQL (FLEXIBLE SERVER)
-- PostgreSQL 14+. Sin dependencias de ningún proveedor: solo PostgreSQL estándar.
--
-- ⚠️  SOLO PARA UNA BASE NUEVA O VACÍA. No borra nada (no hay DROP), pero tampoco es
--     idempotente: ejecutarlo dos veces falla en CREATE TABLE.
--
-- ANTES DE EJECUTARLO (una sola vez, como administrador del servidor):
--   Portal de Azure -> servidor -> "Server parameters" -> azure.extensions:
--   habilita BTREE_GIST (la usa la restricción anti-solape de reservas).
--
-- Ejecución:  psql "$DATABASE_URL_ADMIN" -v ON_ERROR_STOP=1 -f db/azure/schema.sql
--
-- MODELO DE ACCESO
--   * La API NO ejecuta SQL libre: solo llama a procedimientos almacenados sp_*
--     (funciones SECURITY DEFINER con search_path fijo). Todo lo que la API puede
--     hacer con los datos está listado en la sección 6.
--   * La API se conecta con un rol (renfi_app) que SOLO tiene EXECUTE sobre sp_*:
--     no puede leer ni escribir tablas ni vistas directamente (sección 8).
--   * Quién puede qué (admin / cliente / dueño de finca, propiedad de cada
--     recurso) lo decide la capa de servicios (src/services) con el JWT: la base
--     no conoce usuarios finales. Las restricciones CHECK / EXCLUDE y los
--     triggers son la última barrera si un dato inválido llega a la base.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;

