-- La URL pública se calcula en la API con AZURE_STORAGE_ACCOUNT_URL + contenedor.
CREATE TABLE "Imagen" (
    "IdImagen"         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RutaStorage"      VARCHAR(300) NOT NULL,
    "IdFinca"          INT REFERENCES "Finca"("IdFinca") ON UPDATE CASCADE ON DELETE CASCADE,
    "Orden"            INT     NOT NULL DEFAULT 0,
    "EsPortada"        BOOLEAN NOT NULL DEFAULT FALSE,
    "TextoAlternativo" VARCHAR(200),
    "TipoMime"         VARCHAR(50),
