    "PagoMixto"          BOOLEAN DEFAULT FALSE
);

CREATE TABLE "Reserva" (
    "IdReserva"              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "IdFinca"                INT REFERENCES "Finca"("IdFinca") ON UPDATE CASCADE ON DELETE CASCADE,
    "NumeroDocumentoUsuario" INT REFERENCES "Usuario"("NumeroDocumento") ON UPDATE CASCADE ON DELETE SET NULL,
